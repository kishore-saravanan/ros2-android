#!/usr/bin/env python3
"""Maintainer: regenerate THIRD-PARTY-NOTICES.md from lock files and prepared sources.

Needs the prepared native SDK (native-deps/src and staged libraries) and, for the
micro-ROS Agent rows, its build tree. Licenses are those declared by upstream package
metadata/license files at the pinned inputs; review the result before a release.
"""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SPDX = {'apache license 2.0': 'Apache-2.0', 'apache 2.0': 'Apache-2.0', 'apache-2.0': 'Apache-2.0',
        'apache 2.0 license': 'Apache-2.0', 'bsd-3-clause': 'BSD-3-Clause', 'mit': 'MIT',
        'eclipse public license 2.0': 'EPL-2.0', 'eclipse distribution license 1.0': 'BSD-3-Clause (EDL-1.0)',
        'bsd': 'BSD (as declared)'}
# Staged libraries whose names do not start with their package name.
LIBRARY_ALIASES = {'cyclonedds': ('libddsc.so', 'libcycloneddsidl.so'), 'libyaml_vendor': ('libyaml.so',)}


def packages(source):
    found = []
    for manifest in sorted(source.rglob('package.xml')):
        try:
            tree = ET.parse(manifest)
        except ET.ParseError:
            continue
        name = tree.findtext('name', '').strip()
        licenses = [SPDX.get(item.text.strip().lower(), item.text.strip()) for item in tree.findall('license') if item.text]
        found.append((name, licenses))
    return found


def shipped(names, libraries):
    for name in names:
        aliases = LIBRARY_ALIASES.get(name, ())
        if any(lib == f'lib{name}.so' or lib.startswith(f'lib{name}__') or lib in aliases for lib in libraries):
            return True
    return False


def git_revision(path):
    result = subprocess.run(['git', '-C', str(path), 'rev-parse', 'HEAD'], capture_output=True, text=True)
    return result.stdout.strip()[:12] if result.returncode == 0 else 'unknown'


def generate(native, agent_build, ndk_version):
    lock = json.loads((ROOT / 'native/ros-sources.lock.json').read_text())
    python = json.loads((ROOT / 'native/python-runtime.lock.json').read_text())
    shell = json.loads((ROOT / 'native/ros-shell-packages.lock.json').read_text())
    libraries = sorted(path.name for path in (native / 'apk-libs/arm64-v8a').glob('*.so'))
    if not libraries:
        raise RuntimeError('Prepare the native SDK first: no staged APK libraries found')
    agent_tag = re.search(r'--branch (v[\d.]+) https://github.com/eProsima/Micro-XRCE-DDS-Agent',
                          (ROOT / 'setup/build-micro-ros-agent.sh').read_text())[1]
    kotlin = re.search(r'org\.jetbrains\.kotlin\.android"\) version "([^"]+)"', (ROOT / 'build.gradle.kts').read_text())[1]
    yaml_version = re.search(r'find_package\(yaml (\d+\.\d+\.\d+)', (native / 'src/libyaml_vendor/CMakeLists.txt').read_text())[1]
    out = ['# Third-party notices', '',
           'Generated by `setup/generate-notices.py` from the checked-in locks and the prepared',
           'native SDK. It lists components that ROS2 Android builds into its APKs, with the',
           'licenses their upstream metadata declares at the pinned inputs. Full license and',
           'notice texts ship inside each APK under `assets/licenses/` and appear in the app at',
           'Settings → About → Open-source licenses. This is an engineering inventory, not',
           'legal advice; review it before publishing binaries.', '',
           'Original ROS2 Android code is Apache-2.0; see [LICENSE](LICENSE) and [NOTICE](NOTICE).', '',
           '## ROS 2 Jazzy native stack (main app and every runner)', '',
           'Pinned in [native/ros-sources.lock.json](native/ros-sources.lock.json). "In main APK"',
           'means the reference main app and C++ runners package at least one shared library from',
           'that source. Embedded Python runners additionally package rclpy and the Python',
           'message support; the remaining rows are build-time generators or tools. All rows\'',
           'license texts are included in the APKs.', '',
           '| Source | Revision | Declared licenses | In main APK |', '| --- | --- | --- | --- |']
    for repository in lock:
        found = packages(native / 'src' / repository['directory'])
        declared = sorted({license for _, licenses in found for license in licenses}) or ['see staged texts']
        names = [name for name, _ in found]
        out.append(f"| [{repository['directory']}]({repository['url'].removesuffix('.git')}) | "
                   f"`{repository['revision'][:12]}` | {', '.join(declared)} | {'yes' if shipped(names, libraries) else 'build-time'} |")
    out += ['', '## Other native components', '',
            '| Component | Version | License | Where |', '| --- | --- | --- | --- |',
            f'| [libyaml](https://github.com/yaml/libyaml) via libyaml_vendor | {yaml_version} | MIT | main app and runners |',
            f'| LLVM libc++ (`libc++_shared.so`, Android NDK) | NDK {ndk_version} | Apache-2.0 WITH LLVM-exception (plus legacy NCSA terms) | main app and runners |',
            f'| Kotlin standard library | {kotlin} | Apache-2.0 | main app and runners |', '',
            '## micro-ROS Agent (main app)', '',
            f'Built from [Micro-XRCE-DDS-Agent](https://github.com/eProsima/Micro-XRCE-DDS-Agent) `{agent_tag}`.',
            'Its superbuild selects some dependencies by branch, so the exact revisions below are',
            'those of the reference build, not a reproducible lock.', '',
            '| Component | Revision | License |', '| --- | --- | --- |',
            f'| Micro XRCE-DDS Agent | `{agent_tag}` | Apache-2.0 |']
    rows = (('Fast DDS', 'fastdds/src/fastdds', 'Apache-2.0'), ('Fast CDR', 'fastcdr/src/fastcdr', 'Apache-2.0'),
            ('foonathan memory', 'foonathan_memory/src/foonathan_memory', 'Zlib'), ('spdlog', 'spdlog/src/spdlog', 'MIT'))
    for label, relative, license in rows:
        revision = git_revision(agent_build / relative) if agent_build else 'unknown'
        out.append(f'| {label} | `{revision}` | {license} |')
    thirdparty = agent_build / 'fastdds/src/fastdds/thirdparty' if agent_build else None
    asio = re.search(r'#\s*define ASIO_VERSION (\d+)', (thirdparty / 'asio/asio/include/asio/version.hpp').read_text())[1] \
        if thirdparty else None
    tinyxml = '.'.join(re.findall(r'TIXML2_(?:MAJOR|MINOR|PATCH)_VERSION = (\d+)', (thirdparty / 'tinyxml2/tinyxml2.h').read_text())) \
        if thirdparty else None
    asio_version = f'{int(asio) // 100000}.{int(asio) // 100 % 1000}.{int(asio) % 100}' if asio else 'unknown'
    out += [f'| asio (vendored by Fast DDS) | {asio_version} | BSL-1.0 |',
            f'| TinyXML-2 (vendored by Fast DDS) | {tinyxml or "unknown"} | Zlib |',
            '| android-ifaddrs (vendored by Fast DDS) | vendored | BSD-2-Clause |', '',
            '## Embedded Python runner', '',
            'Built locally when you build a Python project; the platform release artifacts do not',
            'contain these binaries. Distributors of Python runner APKs must carry their notices.', '',
            '| Component | Version | License |', '| --- | --- | --- |',
            f"| [Chaquopy](https://github.com/chaquo/chaquopy) Gradle plugin and runtime | {python['chaquopyPlugin']} | MIT |",
            f"| CPython (Chaquopy target) | {python['python']} | PSF-2.0 |",
            f"| NumPy | {python['numpy']} | BSD-3-Clause |",
            f"| PyYAML | {python['pyyaml']} | MIT |", '',
            '## Optional workspace shell', '',
            'Workspace runners built with the shell bundle also contain a standalone Android Python',
            'interpreter and these upstream ROS CLI packages (versions from',
            '[native/ros-shell-packages.lock.json](native/ros-shell-packages.lock.json)):', '',
            ', '.join(f'{name} {version}' for name, version in sorted(shell['rosPackages'].items())) + '.', '',
            'Their pure-Python dependencies are copied from the build host and are not version-',
            'locked: ' + ', '.join(sorted(shell['purePythonDependencies'])) + '. Declared licenses',
            'include Apache-2.0, BSD, MIT and PSF variants; EmPy (`em`) is LGPL-2.1 and docutils is',
            'mixed public-domain/BSD. Review the bundled files before distributing such an APK.', '',
            '## Host client', '',
            'The `ros2-android` wheel has no third-party runtime dependencies. The optional',
            '`inspection` extra installs catkin_pkg (BSD-3-Clause).', '']
    return '\n'.join(out)


def main(arguments=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--agent-build', type=Path,
                        default=Path(os.environ.get('ROS2_ANDROID_AGENT_CACHE', Path.home() / '.cache/ros2-android-esp32')) / 'agent-android')
    parser.add_argument('--output', type=Path, default=ROOT / 'THIRD-PARTY-NOTICES.md')
    parser.add_argument('--check', action='store_true', help='Fail if the output file differs instead of writing it')
    args = parser.parse_args(arguments)
    ndk_version = json.loads((ROOT / 'python/ros2android/compatibility.json').read_text())['android']['ndk']
    agent = args.agent_build if args.agent_build.is_dir() else None
    try:
        text = generate((ROOT / 'native-deps').resolve(), agent, ndk_version)
    except (OSError, RuntimeError, TypeError) as error:
        print('generate notices: ' + str(error), file=sys.stderr)
        return 1
    if args.check:
        current = args.output.read_text() if args.output.is_file() else ''
        if current != text:
            print(f'{args.output} is out of date; rerun setup/generate-notices.py', file=sys.stderr)
            return 1
        return 0
    args.output.write_text(text)
    print(f'Wrote {args.output}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
